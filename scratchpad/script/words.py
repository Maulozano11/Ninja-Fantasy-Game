def raster(strokes, dots, Wd=32, H=18, s=1.0):
    g = [[0] * int(Wd * s) for _ in range(int(H * s))]
    for pts, w0, w1 in strokes:
        n = len(pts)
        for i in range(n - 1):
            (x0, y0), (x1, y1) = pts[i], pts[i + 1]
            for k in range(6):
                t = k / 6
                x, y = (x0 + (x1 - x0) * t) * s, (y0 + (y1 - y0) * t) * s
                r = (w0 + (w1 - w0) * (i + t) / max(1, n - 1)) * s * 1.5 / 2
                for yy in range(int(y - r - 1), int(y + r + 2)):
                    for xx in range(int(x - r - 1), int(x + r + 2)):
                        if 0 <= yy < len(g) and 0 <= xx < len(g[0]) and (xx + .5 - x) ** 2 + (yy + .5 - y) ** 2 <= r * r + .2: g[yy][xx] = 1
    for x, y in dots:
        r = 1.1 * s * 1.5 / 1.5
        for yy in range(int(y * s - r - 1), int(y * s + r + 2)):
            for xx in range(int(x * s - r - 1), int(x * s + r + 2)):
                if 0 <= yy < len(g) and 0 <= xx < len(g[0]) and (xx + .5 - x * s) ** 2 + (yy + .5 - y * s) ** 2 <= r * r + .2: g[yy][xx] = 1
    return g
