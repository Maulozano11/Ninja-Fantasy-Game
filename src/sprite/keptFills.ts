const AS_DRAWN = new Map<string, Set<number>>();
for (const [who, pose, frame, x, y] of LEFT_AS_DRAWN) {
  const key = `${who} ${pose} ${frame}`;
  AS_DRAWN.set(key, (AS_DRAWN.get(key) ?? new Set()).add(y * GRID + x));
}

/** Whether a pixel of this character's frame is to be left as he drew it. */
export function leftAsDrawn(who: string, pose: SpritePose, frame: number, i: number): boolean {
  return !!AS_DRAWN.get(`${who} ${pose} ${frame}`)?.has(i);
}

/** Whether a pocket (its pixels) of this character's frame is one he left filled. */
export function keptFill(who: string, pose: SpritePose, frame: number, px: number[]): boolean {
  const at = BY_FRAME.get(`${who} ${pose} ${frame}`);
  return !!at && at.some((i) => px.includes(i));
}
