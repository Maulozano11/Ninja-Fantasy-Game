// Clean viewport screenshots of the mission prototype for the owner.
import { chromium } from '../pw/node_modules/playwright/index.mjs';
const b = await chromium.launch();
const K = 'shinobi5e.mission.v1';
const errors = [];
const p = await b.newPage({ viewport: { width: 1440, height: 1100 } });
p.on('pageerror', (e) => errors.push(e.message));
await p.goto('http://127.0.0.1:3017/#missions');
await p.evaluate(() => localStorage.clear());
await p.reload();
await p.waitForTimeout(1500);
await p.getByRole('button', { name: /Bring/ }).first().click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'final-1-aldea.png' });
await p.getByRole('button', { name: /Set out with/ }).click();
await p.waitForTimeout(600);
await p.evaluate((k) => {
  const r = JSON.parse(localStorage.getItem(k));
  r.pos = { zone: 1, node: 1 }; r.battle = null; r.nodeDone = false; r.zoneEnd = false;
  Object.assign(r.party.progress, { zone: 1, hoursSpent: 9, hoursSinceCamp: 9, stopsTaken: [0] });
  const m = r.party.members;
  Object.assign(m[0], { currentHp: 21, currentChakra: 12, tension: 4, hitDiceSpent: 2, effects: [{ id: 'sharpened', remaining: 2 }, { id: 'bleeding', source: 'Kunai' }] });
  Object.assign(m[1], { currentHp: 14, currentChakra: 30, tension: 2 });
  Object.assign(m[2], { currentHp: 9, currentChakra: 6, tension: 6, exhaustion: 1, effects: [{ id: 'poisoned', sinceCamp: 0 }] });
  Object.assign(m[3], { currentHp: 30, currentChakra: 10, tension: 3 });
  r.entry = r.party;
  localStorage.setItem(k, JSON.stringify(r));
}, K);
await p.reload();
await p.waitForTimeout(1200);
await p.getByRole('button', { name: /Make camp/ }).click();
await p.waitForTimeout(1200);
const toCamp = async () => {
  await p.evaluate(() => {
    const h = [...document.querySelectorAll('h2')].find((x) => x.textContent === 'Shrine Clearing');
    if (h) window.scrollTo(0, h.getBoundingClientRect().top + window.scrollY - 110);
  });
  await p.waitForTimeout(500);
};
await toCamp();
await p.screenshot({ path: 'final-2-fuego.png' });
await p.getByRole('button', { name: /Katon fire by/ }).first().click();
await p.waitForTimeout(800);
await p.getByRole('button', { name: 'Select Hana' }).click();
await p.getByRole('button', { name: /^Bandage/ }).click();
await p.waitForTimeout(400);
await toCamp();
await p.screenshot({ path: 'final-3-actividades.png' });
await p.getByRole('button', { name: /^Solen Valcaire \d+\/\d+$/ }).click();
await p.getByRole('button', { name: /^Do it/ }).click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: /^Heal with jutsu/ }).click();
await p.getByRole('button', { name: /^Kenji \d+\/\d+$/ }).click();
await p.getByRole('button', { name: /^Do it/ }).click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: 'Select Kenji' }).click();
await p.getByRole('button', { name: /^Wood shelter/ }).click();
await p.getByRole('button', { name: /^Do it/ }).click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: 'Select Solen Valcaire' }).click();
await p.getByRole('button', { name: /^Keep watch/ }).click();
await p.getByRole('button', { name: /^Do it/ }).click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: /Go to dinner/ }).click();
await p.getByRole('button', { name: /^Hot meal/ }).click();
await p.waitForTimeout(800);
await toCamp();
await p.screenshot({ path: 'final-4-noche.png' });
await p.getByRole('button', { name: /^Sleep$/ }).click();
await p.waitForTimeout(800);
const wake = p.getByRole('button', { name: /Wake up/ });
if (await wake.count()) { await wake.click(); await p.waitForTimeout(1200); }
await toCamp();
await p.screenshot({ path: 'final-5-amanecer.png' });
console.log(errors.join('\n') || 'no errors');
await b.close();
