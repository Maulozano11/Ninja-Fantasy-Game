// every art pixel, so a font pixel is 2 screen pixels like the frames around it).
//
//   title  cap 7, x-height 5, descender 2 (names, the target bar)
//   label  cap 6, x-height 4, descender 2 (small labels and numbers)
//   big    10 rows, 2-pixel strokes, digits only (the round number)
//
// Spanish letters with acute accents and n-tilde are built from the base letters.

