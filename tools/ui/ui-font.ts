export const FONTS = { title: TITLE, label: LABEL, big: BIG };
export type FontName = keyof typeof FONTS;

// Accented letters: the base letter with an acute (or a tilde) laid over its top rows.
function accent(f: Font, base: string, mark: 'acute' | 'tilde'): string[] {
  const rows = f.glyphs[base].map((r) => r.split(''));
  const w = rows[0].length;
  if (base === 'i') {
    // The stem stays in column 0; the accent leans right of it, where the dot was.
    const out = rows.map((r) => [...r, '.']);
    out[0] = ['.', '#'];
    if (f === TITLE) out[1] = ['#', '.'];
    return out.map((r) => r.join(''));
  }
  const mid = Math.floor(w / 2);
  if (f === TITLE) {
    if (mark === 'acute') {
      rows[0] = rows[0].map((_, x) => (x === mid + 1 ? '#' : '.'));
      rows[1] = rows[1].map((_, x) => (x === mid ? '#' : '.'));
    } else {
      rows[0] = rows[0].map((_, x) => (x === 1 || x === 2 || x === 4 ? '#' : '.'));
      rows[1] = rows[1].map((_, x) => (x === 0 || x === 3 ? '#' : '.'));
    }
  } else if (mark === 'acute') {
    rows[0] = rows[0].map((_, x) => (x === Math.min(w - 1, mid + 1) ? '#' : '.'));
  } else {
    rows[0] = rows[0].map((_, x) => (x === 1 || x === 3 ? '#' : '.'));
    rows[1] = rows[1].map((_, x) => (x === 0 || x === 2 ? '#' : '.'));
  }
  return rows.map((r) => r.join(''));
}
for (const f of [TITLE, LABEL]) {
  for (const [ch, base] of [['á', 'a'], ['é', 'e'], ['í', 'i'], ['ó', 'o'], ['ú', 'u']] as const) f.glyphs[ch] = accent(f, base, 'acute');
  f.glyphs['ñ'] = accent(f, 'n', 'tilde');
}

function glyph(f: Font, ch: string): string[] | null {
  return f.glyphs[ch] ?? f.glyphs[ch.toUpperCase()] ?? null;
}

/** Width in art pixels of `s` in font `name` (1 pixel between letters). */
export function textWidth(s: string, name: FontName): number {
  const f = FONTS[name];
  let w = 0;
  for (const ch of s) {
    const gl = ch === ' ' ? null : glyph(f, ch);
    w += (gl ? gl[0].length : f.space) + 1;
  }
  return Math.max(0, w - 1);
}

export interface TextStyle {
  color: RGBA;
  /** A 1-pixel ring around the letters (8 neighbours). */
  outline?: RGBA;
  /** A copy one pixel lower, under the letters (and under the outline). */
  shadow?: RGBA;
  /** The top row(s) of each letter in this color (a lit edge). */
  top?: RGBA;
}

/**
 * Renders `s` as an art-pixel image with a 1-pixel margin (for the outline and shadow). The
 * baseline sits at row `1 + font.base`.
 */
export function renderText(s: string, name: FontName, st: TextStyle): Img {
  const f = FONTS[name];
  const w = textWidth(s, name) + 2, h = f.rows + 3;
  const ink = new Uint8Array(w * h);
  let x = 1;
  for (const ch of s) {
    const gl = ch === ' ' ? null : glyph(f, ch);
    if (gl) {
      for (let r = 0; r < gl.length; r++) for (let c = 0; c < gl[r].length; c++) if (gl[r][c] === '#') ink[(1 + r) * w + x + c] = 1;
      x += gl[0].length + 1;
    } else x += f.space + 1;
  }
  const out = new Img(w, h);
  const at = (xx: number, yy: number) => xx >= 0 && yy >= 0 && xx < w && yy < h && ink[yy * w + xx] === 1;
  if (st.shadow)
    for (let yy = 0; yy < h; yy++)
      for (let xx = 0; xx < w; xx++) {
        if (at(xx, yy - 1)) out.set(xx, yy, st.shadow);
        else if (st.outline && (at(xx - 1, yy - 1) || at(xx + 1, yy - 1) || at(xx, yy - 2))) out.set(xx, yy, st.shadow);
      }
  if (st.outline)
    for (let yy = 0; yy < h; yy++)
      for (let xx = 0; xx < w; xx++) {
        if (at(xx, yy)) continue;
        let n = false;
        for (let dy = -1; dy <= 1 && !n; dy++) for (let dx = -1; dx <= 1; dx++) if (at(xx + dx, yy + dy)) n = true;
        if (n) out.set(xx, yy, st.outline);
      }
  for (let yy = 0; yy < h; yy++)
    for (let xx = 0; xx < w; xx++) if (at(xx, yy)) out.set(xx, yy, st.top && !at(xx, yy - 1) ? st.top : st.color);
  return out;
}

/** Text at screen scale: rendered in art pixels, then each pixel doubled (2x2), with a dark outline. */
export function screenText(s: string, font: FontName, color: RGBA, outline: RGBA | undefined = DARK, shadow?: RGBA): Img {
  return renderText(s, font, { color, outline, shadow }).scaled(2);
}
const DARK: RGBA = [11, 8, 5, 255];
