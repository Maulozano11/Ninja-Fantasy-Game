await page.waitForFunction(() => { const s = window.__battle.state(); const u = s.units[s.order[s.turn]]; return !window.__battle.busy() && u?.team === 'party' && u.controller === 'player'; }, null, { timeout: 120000 });
await page.waitForTimeout(600);
// The ninja whose turn it is becomes a Kōton (its clan abilities first, as unitFrom gives them).
const info = await page.evaluate(() => {
  const b = window.__battle;
  const s = b.state();
  const u = s.units[s.order[s.turn]];
  u.character = { ...u.character, clan: 'Koton' };
  u.jutsus = ['koton_block', 'koton_wall', ...u.jutsus.filter((j) => !j.startsWith('mirai_') && !j.startsWith('katon_') && !j.startsWith('koton_'))];
  u.turn = { move: u.speed, action: true, bonus: true, reaction: true, moved: 0 };
  u.chakra = Math.max(u.chakra, 20);
  b.act({ type: 'setController', unit: u.id, controller: 'player' });
  b.centerOn(u.pos.x + 3, u.pos.z);
  const foes = Object.values(s.units).filter((e) => e.team === 'enemy' && !e.down);
  return { id: u.id, name: u.name, pos: u.pos, jutsus: u.jutsus, foes: foes.map((e) => [e.id, e.pos]) };
});
console.log(JSON.stringify(info));
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/1-tip-${locale}.png` });
const at = (x, z) => page.evaluate(([x, z]) => window.__battle.screenOf(x, z), [x, z]);
