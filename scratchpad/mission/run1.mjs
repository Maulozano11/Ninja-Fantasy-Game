import { chromium } from '../pw/node_modules/playwright/index.mjs';
const URL = 'http://127.0.0.1:3017/#missions';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
p.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
await p.goto(URL);
await p.evaluate(() => localStorage.clear());
await p.reload();
await p.waitForTimeout(2500);
await p.screenshot({ path: '01-village.png', fullPage: true });
await p.getByRole('button', { name: /Set out with/ }).click();
await p.waitForTimeout(1500);
await p.screenshot({ path: '02-road-battle-prep.png', fullPage: true });
await p.getByRole('button', { name: /^Fight$/ }).click();
await p.waitForTimeout(2500);
await p.screenshot({ path: '03-battle.png' });
console.log(errors.join('\n') || 'no errors');
await b.close();
