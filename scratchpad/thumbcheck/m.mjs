import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const [out, vw, vh] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: +vw, height: +vh }, deviceScaleFactor: 1, locale: 'es-MX' });
await page.goto('http://127.0.0.1:5287/', { waitUntil: 'networkidle' });
await page.getByText('Nueva partida').first().click();
await page.waitForTimeout(1500);
await page.getByText('Aiden, el Caballero Carmesí').first().click();
await page.waitForTimeout(600);
await page.getByRole('button', { name: /apariencia/i }).first().click();
await page.waitForTimeout(800);
await page.getByRole('button', { name: /^arma$/i }).first().click();
await page.waitForTimeout(800);
const steel = page.getByText('Acero', { exact: true }).first();
await steel.scrollIntoViewIfNeeded();
await page.waitForTimeout(400);
const info = await page.evaluate(() => [...document.querySelectorAll('canvas')].filter(c => c.width === 67 || (c.style.maxWidth === '100%')).map(c => { const r = c.getBoundingClientRect(); return { w: c.width, h: c.height, cssW: r.width, cssH: r.height, x: r.x, y: r.y, parentW: c.parentElement.getBoundingClientRect().width }; }));
console.log(JSON.stringify(info, null, 0));
await page.screenshot({ path: `${out}/shot-${vw}.png` });
await browser.close();
